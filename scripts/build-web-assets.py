#!/usr/bin/python3
"""Rebuild web-only font derivatives and pixel-identical screen deliveries.
The original desktop font, license and captured PNGs remain unchanged.
"""
from pathlib import Path
import argparse, hashlib, json
from PIL import Image
from fontTools import subset
from fontTools.ttLib import TTFont
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--verify-existing',action='store_true',help='Validate the exact current outputs without compression or writes')
parser.add_argument('--refresh-input-hashes',action='store_true',help='With verification, update only source hashes after proving all generated bytes and character sets match')
parser.add_argument('--write-font-style-split',action='store_true',help='Bootstrap the exact core/extra CSS split after verifying all existing assets')
args=parser.parse_args(); VERIFY=args.verify_existing
assert not args.write_font_style_split or (VERIFY and args.refresh_input_hashes), '--write-font-style-split requires verification and source-hash refresh'
assert not args.refresh_input_hashes or VERIFY, '--refresh-input-hashes requires --verify-existing'
ROOT=Path(__file__).resolve().parent.parent
FONT=ROOT/'assets/fonts/LXGWWenKaiMonoGB-Regular.ttf'
out=ROOT/'assets/fonts/web'; out.mkdir(exist_ok=True)
source=TTFont(FONT,recalcTimestamp=False); available=set(source.getBestCmap())
# Fixed public UI inputs: adding a loader or unrelated root file must not repartition the font.
INPUTS=('app.js','coi-bootstrap.js','coi-serviceworker.js','flasher.css','flasher.js',
        'index.html','install-loader.js','legal.html','media.js','real-flasher-ui.js',
        'style.css','v2.css','v2.js')
input_hashes={name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in (*INPUTS,'scripts/build-web-assets.py','scripts/web-font-core-codepoints.json')}
text=''.join((ROOT/name).read_text() for name in INPUTS)
# Keep the measured critical font stable when secondary UI/attribution text changes.
# This versioned source allocation came from the deployed 7aa22e4 CSS, not current outputs.
allocation=json.loads((ROOT/'scripts/web-font-core-codepoints.json').read_text())
assert allocation['schema']==1 and allocation['baseline']=='7aa22e47fe160668a06620e5855df85675214c19'
core=set(allocation['codepoints'])
assert len(core)==855 and core<=available
parts=[('core',core)]
remaining=available-core
for block in sorted({cp//1024 for cp in remaining}):
    parts.append((f'u{block*1024:05x}',{cp for cp in remaining if cp//1024==block}))
def ranges(points):
    spans=[]
    for cp in sorted(points):
        if spans and cp==spans[-1][1]+1: spans[-1][1]=cp
        else: spans.append([cp,cp])
    return ','.join(f'U+{a:X}'+(f'-{b:X}' if a!=b else '') for a,b in spans)
css=[]; records=[]
for name,points in parts:
    dest=out/f'{name}.woff2'
    font=TTFont(dest,recalcTimestamp=False) if dest.exists() else None
    if font is None or set(font.getBestCmap())!=points:
        assert not VERIFY, f'{dest}: missing or stale cmap'
        font=TTFont(FONT,recalcTimestamp=False); options=subset.Options(); options.flavor='woff2'; options.recalc_timestamp=False; options.name_IDs=['*']; options.name_languages=['*']
        sub=subset.Subsetter(options=options); sub.populate(unicodes=points); sub.subset(font)
        font.flavor='woff2'; font.save(dest)
    if font['head'].modified!=source['head'].modified:
        assert not VERIFY, f'{dest}: stale timestamp'
        font['head'].modified=source['head'].modified; font.save(dest)
    assert set(font.getBestCmap())==points
    # Subsetting must retain every requested glyph outline and advance exactly.
    for cp in points:
        old=source.getBestCmap()[cp]; new=font.getBestCmap()[cp]
        assert source['hmtx'][old]==font['hmtx'][new]
        assert source['glyf'][old].getCoordinates(source['glyf'])==font['glyf'][new].getCoordinates(font['glyf'])
        a=getattr(source['glyf'][old],'program',None); b=getattr(font['glyf'][new],'program',None)
        assert (a.getBytecode() if a else None)==(b.getBytecode() if b else None)
    css.append("@font-face{font-family:'Zhijian WenKai';src:url('web/"+name+".woff2') format('woff2');font-weight:400;font-style:normal;font-display:swap;unicode-range:"+ranges(points)+'}')
    records.append({'file':str(dest.relative_to(ROOT)),'bytes':dest.stat().st_size,'codepoints':len(points),'sha256':hashlib.sha256(dest.read_bytes()).hexdigest()})
style_texts={'assets/fonts/web-fonts.css':'\n'.join(css)+'\n',
             'assets/fonts/web-fonts-core.css':css[0]+'\n',
             'assets/fonts/web-fonts-extra.css':'\n'.join(css[1:])+'\n'}
assert style_texts['assets/fonts/web-fonts-core.css']+style_texts['assets/fonts/web-fonts-extra.css']==style_texts['assets/fonts/web-fonts.css']
for name,value in style_texts.items():
    if VERIFY:
        if not (args.write_font_style_split and name!='assets/fonts/web-fonts.css'):
            assert (ROOT/name).read_bytes()==value.encode(), f'stale font CSS: {name}'
    else: (ROOT/name).write_bytes(value.encode())
styles=[{'file':name,'bytes':len(value.encode()),'sha256':hashlib.sha256(value.encode()).hexdigest()} for name,value in style_texts.items()]
images=[]
for path in sorted((ROOT/'assets/screens').glob('*.png')):
    before=Image.open(path).convert('RGBA'); dest=ROOT/'assets/screens-web'/f'{path.stem}.webp'
    if not VERIFY: before.save(dest,'WEBP',lossless=True,method=6,exact=True)
    after=Image.open(dest).convert('RGBA')
    assert before.size==after.size and before.tobytes()==after.tobytes(), path
    images.append({'source':str(path.relative_to(ROOT)),'file':str(dest.relative_to(ROOT)),'sourceBytes':path.stat().st_size,'bytes':dest.stat().st_size,'size':list(before.size),'rgbaSha256':hashlib.sha256(after.tobytes()).hexdigest(),'sourceSha256':hashlib.sha256(path.read_bytes()).hexdigest(),'sha256':hashlib.sha256(dest.read_bytes()).hexdigest()})
manifest={'fontSourceSha256':hashlib.sha256(FONT.read_bytes()).hexdigest(),'fontSourceBytes':FONT.stat().st_size,'fontInputs':input_hashes,'fontCodepoints':len(available),'fontParts':records,'fontStyles':styles,'screens':images}
manifest_path=ROOT/'assets/web-assets-manifest.json'; manifest_text=json.dumps(manifest,ensure_ascii=False,indent=2)+'\n'
if VERIFY:
    previous=json.loads(manifest_path.read_text())
    if args.refresh_input_hashes:
        previous['fontInputs']=input_hashes
        if args.write_font_style_split: previous['fontStyles']=styles
        assert previous==manifest, 'generated assets changed; cannot refresh only input hashes'
        if args.write_font_style_split:
            for name,value in style_texts.items():
                if name!='assets/fonts/web-fonts.css': (ROOT/name).write_bytes(value.encode())
        manifest_path.write_text(manifest_text)
    else: assert previous==manifest, 'stale asset manifest'
else: manifest_path.write_text(manifest_text)
print(json.dumps({'mode':'verify-existing' if VERIFY else 'generate','fontOriginal':manifest['fontSourceBytes'],'fontCore':records[0]['bytes'],'fontAll':sum(x['bytes'] for x in records),'screensOriginal':sum(x['sourceBytes'] for x in images),'screensWeb':sum(x['bytes'] for x in images),'screens':len(images)}))
